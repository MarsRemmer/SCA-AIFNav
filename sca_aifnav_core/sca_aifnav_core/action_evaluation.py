"""One-step Active Inference action evaluation for the V5 baseline."""

from dataclasses import dataclass

import numpy as np

from sca_aifnav_core.generative_model import (
    BaselineGenerativeModel,
)
from sca_aifnav_core.preference_state import (
    BaselinePreferenceState,
)


LOG_EPSILON = 1e-16
STATE_INFO_EPSILON = np.exp(-16.0)


@dataclass(frozen=True)
class ExpectedObservations:
    """Expected observations for the two V5 modalities."""

    sensory: np.ndarray
    place: np.ndarray


@dataclass(frozen=True)
class ActionEvaluation:
    """One-step negative expected-free-energy components."""

    action_id: int
    predicted_state: np.ndarray
    expected_observations: ExpectedObservations
    expected_utility: float
    state_information_gain: float
    score: float


def predict_action_state(
    model: BaselineGenerativeModel,
    state_belief: np.ndarray,
    action_id: int,
) -> np.ndarray:
    """Predict the next hidden-state belief through B."""
    belief = _validated_belief(
        state_belief,
        model.num_states,
    )

    return model.predicted_state_prior(
        action_id=action_id,
        belief=belief,
    )


def predict_observations(
    model: BaselineGenerativeModel,
    state_belief: np.ndarray,
) -> ExpectedObservations:
    """Predict observation distributions through A."""
    belief = _validated_belief(
        state_belief,
        model.num_states,
    )

    sensory = (
        model.sensory_likelihood
        @ belief
    )

    place = (
        model.place_likelihood
        @ belief
    )

    return ExpectedObservations(
        sensory=sensory,
        place=place,
    )


def expected_utility(
    expected_observations: ExpectedObservations,
    preferences: BaselinePreferenceState,
) -> float:
    """
    Compute the V5/pymdp expected utility term.

    Preference vectors are treated as relative log preferences, softmaxed
    before taking their logarithm.
    """
    utility = 0.0

    modality_pairs = (
        (
            expected_observations.sensory,
            preferences.sensory,
        ),
        (
            expected_observations.place,
            preferences.place,
        ),
    )

    for observation_distribution, preference in modality_pairs:
        if observation_distribution.shape != preference.shape:
            raise ValueError(
                "preference and observation dimensions must match"
            )

        preference_probability = _softmax(
            preference
        )

        log_preference = np.log(
            preference_probability
            + LOG_EPSILON
        )

        # AIMAPP's pymdp suppresses the constant term generated by a
        # modality that has no relative preference.
        if len(set(log_preference.tolist())) == 1:
            log_preference = np.zeros_like(
                log_preference
            )

        utility += float(
            observation_distribution.dot(
                log_preference
            )
        )

    return utility


def state_information_gain(
    model: BaselineGenerativeModel,
    state_belief: np.ndarray,
) -> float:
    """
    Compute V5 expected Bayesian surprise about hidden states.

    This is the one-hidden-factor, two-modality equivalent of pymdp's
    spm_MDP_G(A, qs).
    """
    belief = _validated_belief(
        state_belief,
        model.num_states,
    )

    joint_observation_count = (
        model.sensory_observations
        * model.place_observations
    )

    expected_joint_observation = np.zeros(
        joint_observation_count,
        dtype=float,
    )

    information_gain = 0.0

    for state_id, state_probability in enumerate(
        belief
    ):
        if state_probability <= STATE_INFO_EPSILON:
            continue

        sensory_given_state = (
            model.sensory_likelihood[
                :,
                state_id,
            ]
        )

        place_given_state = (
            model.place_likelihood[
                :,
                state_id,
            ]
        )

        joint_given_state = np.kron(
            sensory_given_state,
            place_given_state,
        )

        expected_joint_observation += (
            state_probability
            * joint_given_state
        )

        information_gain += (
            state_probability
            * float(
                joint_given_state.dot(
                    np.log(
                        joint_given_state
                        + STATE_INFO_EPSILON
                    )
                )
            )
        )

    information_gain -= float(
        expected_joint_observation.dot(
            np.log(
                expected_joint_observation
                + STATE_INFO_EPSILON
            )
        )
    )

    return information_gain


def evaluate_action(
    model: BaselineGenerativeModel,
    preferences: BaselinePreferenceState,
    action_id: int,
    state_belief=None,
    use_utility: bool = True,
    use_state_information_gain: bool = True,
) -> ActionEvaluation:
    """Evaluate one candidate action using V5 one-step EFE terms."""
    preferences.sync_dimensions(
        model
    )

    if state_belief is None:
        belief = model.state_belief.copy()
    else:
        belief = _validated_belief(
            state_belief,
            model.num_states,
        )

    predicted_state = predict_action_state(
        model=model,
        state_belief=belief,
        action_id=action_id,
    )

    observations = predict_observations(
        model=model,
        state_belief=predicted_state,
    )

    utility = 0.0

    if use_utility:
        utility = expected_utility(
            expected_observations=observations,
            preferences=preferences,
        )

    information_gain = 0.0

    if use_state_information_gain:
        information_gain = (
            state_information_gain(
                model=model,
                state_belief=predicted_state,
            )
        )

    score = (
        utility
        + information_gain
    )

    return ActionEvaluation(
        action_id=action_id,
        predicted_state=predicted_state,
        expected_observations=observations,
        expected_utility=utility,
        state_information_gain=(
            information_gain
        ),
        score=score,
    )


def _softmax(
    values: np.ndarray,
) -> np.ndarray:
    """Reproduce pymdp's numerically stable softmax."""
    values = np.asarray(
        values,
        dtype=float,
    )

    shifted = (
        values
        - values.max()
    )

    result = np.exp(
        shifted
    )

    return result / result.sum()


def _validated_belief(
    belief: np.ndarray,
    num_states: int,
) -> np.ndarray:
    """Validate one hidden-state belief vector."""
    result = np.asarray(
        belief,
        dtype=float,
    )

    if result.shape != (num_states,):
        raise ValueError(
            "state_belief shape must match number of states"
        )

    if not np.all(np.isfinite(result)):
        raise ValueError(
            "state_belief must contain finite values"
        )

    return result.copy()
